function isoDate(offsetDays: number): string {
  const date = new Date();
  date.setDate(date.getDate() + offsetDays);
  return date.toISOString().slice(0, 10);
}

function author(id: string): PrayerTopicAuthorOption {
  const found = MOCK_AUTHORS.find((candidate) => candidate.id === id);
  if (!found) throw new Error(`Auteur fictif inconnu : ${id}`);
  return found;
}

function nextTimestamp(offsetMinutes: number): string {
  return new Date(Date.now() - offsetMinutes * 60_000).toISOString();
}

